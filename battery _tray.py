import math
from dataclasses import dataclass
from cadquery import func as cf
import trimesh
import plotly.graph_objects as go

# Battery specifications
@dataclass
class CellSpec:
    r_cell: float
    h_cell: float


cells = {
    "18650": CellSpec(9.0, 65.0),
    "21700": CellSpec(10.5, 70.0),
    "4680": CellSpec(23.0, 80.0)
}


# Battery tray function
def battery_tray(cell_name, n):

    spec = cells[cell_name]

    clearance = 0.5
    wall = 3.0
    base = 3.0

    pocket_d = 2 * (spec.r_cell + clearance)
    pocket_depth = spec.h_cell
    pitch = pocket_d + 3.0

    length = (n - 1) * pitch + pocket_d + 2 * wall
    width = pocket_d + 2 * wall
    height = pocket_depth + base

    plate = cf.box(length, width, height)
    pocket = cf.cylinder(d=pocket_d, h=pocket_depth)

    # Create pockets using a loop
    for i in range(n):
        x = (i - (n - 1) / 2) * pitch
        plate = plate - pocket.moved(x=x, z=base)

    return plate, length, width, height


# Generate tray
cell_name = "18650"
n = 3

tray, length, width, height = battery_tray(cell_name, n)


# Calculate expected volume
spec = cells[cell_name]
r = spec.r_cell + 0.5

expected = (
    length * width * height
    - n * math.pi * r**2 * spec.h_cell
)


# Validate model
print("Battery type:", cell_name)
print("Number of pockets:", n)
print("Tray dimensions:", length, "x", width, "x", height, "mm")
print("Valid:", tray.isValid())
print("Actual volume:", round(tray.Volume(), 2))
print("Expected volume:", round(expected, 2))

assert abs(tray.Volume() - expected) < 0.5

print("Battery tray created successfully!")


# Export STL
tray.exportStl("battery_tray.stl")


# Load model for visualization
mesh = trimesh.load("battery_tray.stl", force="mesh")

vertices = mesh.vertices
faces = mesh.faces


# Interactive 3D preview
fig = go.Figure(data=[
    go.Mesh3d(
        x=vertices[:, 0],
        y=vertices[:, 1],
        z=vertices[:, 2],
        i=faces[:, 0],
        j=faces[:, 1],
        k=faces[:, 2],
        color="orange",
        opacity=1
    )
])

fig.update_layout(
    title="Day 10 - 18650 Battery Tray",
    scene=dict(
        xaxis_title="Length (mm)",
        yaxis_title="Width (mm)",
        zaxis_title="Height (mm)",
        aspectmode="manual",
        aspectratio=dict(x=1.4, y=0.65, z=1.4),
        camera=dict(
            eye=dict(x=1.8, y=1.8, z=1.3)
        )
    ),
    width=1000,
    height=700
)

fig.show()

